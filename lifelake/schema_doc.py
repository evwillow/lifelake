def _md_table(headers, rows) -> str:
    out = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    for r in rows:
        out.append("| " + " | ".join("" if v is None else str(v).replace("|", "\\|") for v in r) + " |")
    return "\n".join(out)


def write_schema_md(con, cfg: Config, path: Path | None = None) -> Path:
    path = path or cfg.schema_path
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    tables = [r[0] for r in con.execute(
        "SELECT table_name FROM information_schema.tables WHERE table_schema='main' ORDER BY table_name").fetchall()]
    lines = ["# lifelake schema", "", f"Generated by `lifelake schema` at {now}.", "",
             "Raw files are not copied into the lake; they stay where they are and are only read.", "",
             "## Redaction", "",
             "Applied at ingest to every text field: typed regexes first, then a Shannon-entropy test on candidate "
             "tokens. Each hit becomes `[REDACTED:<type>]`.", ""]
    red = dict(con.execute("SELECT type, sum(hits) FROM redaction_log GROUP BY 1").fetchall())
    lines += [_md_table(["type", "hits (all runs)"], [(t, int(red.get(t, 0))) for t in redaction_types()]), ""]
    lines += ["## Time", "", "Every table stores UTC and a `local_ts` plus `tz` from `tz_periods`:", "",
              _md_table(["tz", "start_utc", "end_utc (excl.)", "note"],
                        [(a, str(b)[:10], str(c)[:10], d) for a, b, c, d in
                         con.execute("SELECT * FROM tz_periods ORDER BY start_utc").fetchall()]), ""]
    lines += ["## Tables", ""]
    for t in tables:
        n = con.execute(f'SELECT count(*) FROM "{t}"').fetchone()[0]
        lines += [f"### {t} ({n:,} rows)", "", TABLE_NOTES.get(t, ""), ""]
        cols = con.execute("""SELECT column_name, data_type FROM information_schema.columns
                              WHERE table_schema='main' AND table_name=? ORDER BY ordinal_position""", [t]).fetchall()
        lines += [_md_table(["column", "type", "notes"], [(c, ty, COLUMN_NOTES.get((t, c), "")) for c, ty in cols]), ""]
    path.write_text("\n".join(lines))
    return path
